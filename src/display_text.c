static inline void set_pixel_color(uint8_t *buf, uint32_t offset,
				   enum display_pixel_format fmt,
				   uint32_t color)
{
	uint8_t r = (color >> 16) & 0xFF;
	uint8_t g = (color >> 8) & 0xFF;
	uint8_t b = color & 0xFF;

	switch (fmt) {
	case PIXEL_FORMAT_RGB_565: {
		uint16_t c565 = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3);
		buf[offset] = (c565 >> 8) & 0xFF;
		buf[offset + 1] = c565 & 0xFF;
		break;
	}
	case PIXEL_FORMAT_BGR_565: {
		uint16_t c565 = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3);
		*(uint16_t *)(buf + offset) = c565;
		break;
	}
	case PIXEL_FORMAT_RGB_888:
		buf[offset] = r;
		buf[offset + 1] = g;
		buf[offset + 2] = b;
		break;
	case PIXEL_FORMAT_ARGB_8888:
		*(uint32_t *)(buf + offset) = 0xFF000000u | color;
		break;
	default:
		buf[offset] = (uint8_t)(((uint16_t)r + g + b) / 3);
		break;
	}
}

const uint8_t *display_glyph_for_char(char ch)
{
	if (ch >= FONT_FIRST_CHAR && ch <= FONT_LAST_CHAR) {
		return font_ascii[ch - FONT_FIRST_CHAR];
	}
	return NULL;
}

uint8_t get_bpp(enum display_pixel_format fmt)
{
	switch (fmt) {
	case PIXEL_FORMAT_ARGB_8888:
		return 4;
	case PIXEL_FORMAT_RGB_888:
		return 3;
	case PIXEL_FORMAT_RGB_565:
	case PIXEL_FORMAT_BGR_565:
		return 2;
	default:
		return 1;
	}
}

uint16_t text_center_x(uint16_t screen_w, uint16_t text_w)
{
	return (screen_w > text_w) ? (screen_w - text_w) / 2 : 0;
}

void display_text(const struct device *dev, const struct display_capabilities *caps,
		  const char *str, uint16_t x_pos, uint16_t y_pos, uint32_t fg_color,
		  uint32_t bg_color, uint8_t *text_buf, uint8_t bpp,
		  int scale_num, int scale_den)
{
	int len = strlen(str);

	if (len > DISPLAY_TEXT_MAX_LEN) {
		len = DISPLAY_TEXT_MAX_LEN;
	}
	if (scale_num < 1) {
		scale_num = 1;
	}
	if (scale_den < 1) {
		scale_den = 1;
	}
	if (scale_num > FONT_SCALE_LARGE_NUM) {
		scale_num = FONT_SCALE_LARGE_NUM;
	}
	if (scale_den > FONT_SCALE_LARGE_DEN) {
		scale_den = FONT_SCALE_LARGE_DEN;
	}

	uint16_t glyph_w = FONT_W * scale_num / scale_den;
	uint16_t glyph_h = FONT_H * scale_num / scale_den;
	if (glyph_w < 1) {
		glyph_w = 1;
	}
	if (glyph_h < 1) {
		glyph_h = 1;
	}

	uint16_t text_w = len * glyph_w;
	uint16_t text_h = glyph_h;
	uint32_t total_px = (uint32_t)text_w * text_h;

	if (bg_color == COLOR_BLACK) {
		(void)memset(text_buf, 0x00, total_px * bpp);
	} else {
		for (uint32_t px = 0; px < total_px; px++) {
			set_pixel_color(text_buf, px * bpp, caps->current_pixel_format, bg_color);
		}
	}

	for (int c = 0; c < len; c++) {
		const uint8_t *glyph = display_glyph_for_char(str[c]);

		if (!glyph) {
			continue;
		}
		if (scale_num == 1 && scale_den == 1) {
			for (int row = 0; row < FONT_H; row++) {
				uint8_t bits = glyph[row];
				for (int col = 0; col < FONT_W; col++) {
					if (bits & (0x80 >> col)) {
						uint32_t px = row * text_w + c * FONT_W + col;
						set_pixel_color(text_buf, px * bpp,
								caps->current_pixel_format, fg_color);
					}
				}
			}
		} else {
			for (int dy = 0; dy < glyph_h; dy++) {
				int src_row = dy * FONT_H / glyph_h;
				uint8_t bits = glyph[src_row];
				for (int dx = 0; dx < glyph_w; dx++) {
					int src_col = dx * FONT_W / glyph_w;
					if (bits & (0x80 >> src_col)) {
						uint32_t px = dy * text_w + (c * glyph_w + dx);
						set_pixel_color(text_buf, px * bpp,
								caps->current_pixel_format, fg_color);
					}
				}
			}
		}
	}

	struct display_buffer_descriptor desc = {
		.buf_size = total_px * bpp,
		.width = text_w,
		.height = text_h,
		.pitch = text_w,
	};

	display_write(dev, x_pos, y_pos, &desc, text_buf);
}

void fill_display_solid(const struct device *dev, const struct display_capabilities *caps,
			uint32_t color)
{
	uint8_t bpp = get_bpp(caps->current_pixel_format);
	const size_t chunk_h = 16;
	size_t chunk_size = caps->x_resolution * chunk_h * bpp;
	uint8_t *chunk = k_malloc(chunk_size);

	if (!chunk) {
		return;
	}
	for (size_t i = 0; i < chunk_size / bpp; i++) {
		set_pixel_color(chunk, i * bpp, caps->current_pixel_format, color);
	}
	struct display_buffer_descriptor desc = {
		.buf_size = chunk_size,
		.width = caps->x_resolution,
		.height = chunk_h,
		.pitch = caps->x_resolution,
	};
	for (size_t y = 0; y < caps->y_resolution; y += chunk_h) {
		desc.height = (caps->y_resolution - y) < chunk_h ? (caps->y_resolution - y) : chunk_h;
		desc.buf_size = desc.width * desc.height * bpp;
		display_write(dev, 0, y, &desc, chunk);
	}
	k_free(chunk);
}

void display_solid_rect(const struct device *dev, const struct display_capabilities *caps,
			uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint32_t color)
{
	if (w == 0U || h == 0U) {
		return;
	}
	if ((uint32_t)x + (uint32_t)w > caps->x_resolution || (uint32_t)y + (uint32_t)h > caps->y_resolution) {
		return;
	}

	uint8_t bpp = get_bpp(caps->current_pixel_format);
	size_t pixels = (size_t)w * (size_t)h;
	size_t buf_sz = pixels * bpp;
	uint8_t *buf = k_malloc(buf_sz);

	if (!buf) {
		return;
	}
	for (size_t i = 0; i < pixels; i++) {
		set_pixel_color(buf, i * bpp, caps->current_pixel_format, color);
	}
	struct display_buffer_descriptor desc = {
		.buf_size = buf_sz,
		.width = w,
		.height = h,
		.pitch = w,
	};

	display_write(dev, x, y, &desc, buf);
	k_free(buf);
}
